#!/usr/bin/env python3
"""Generate controlled matched-pair personas from the benchmark protocol."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import tempfile
from collections import Counter
from pathlib import Path
from typing import Any, Sequence

import yaml


PACKAGE_DIR = Path(__file__).resolve().parent
REPO_ROOT = PACKAGE_DIR.parent
DEFAULT_PROTOCOL_PATH = PACKAGE_DIR / "persona_experiment.json"
DEFAULT_TASKS_PATH = PACKAGE_DIR / "tasks.json"
DEFAULT_OUTPUT_DIR = PACKAGE_DIR / "personas" / "matched_pairs"
DEFAULT_SCHEMA_PATH = PACKAGE_DIR / "dimensions.json"

HEADER = """# CONTROLLED MATCHED-PAIR PROFILE — synthetic experiment fixture.
# Generated by personacuabench.make_matched_personas; edit the protocol, not this file.
"""


class ExperimentDefinitionError(ValueError):
    """Raised when the experiment protocol is internally inconsistent."""


def _load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as exc:
        raise ExperimentDefinitionError(f"File not found: {path}") from exc
    except json.JSONDecodeError as exc:
        raise ExperimentDefinitionError(f"Invalid JSON {path}: {exc}") from exc


def _file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _catalog(path: Path) -> dict[str, set[str]]:
    payload = _load_json(path)
    rows = payload.get("dimensions") if isinstance(payload, dict) else None
    if not isinstance(rows, list):
        raise ExperimentDefinitionError(f"Schema has no dimensions list: {path}")
    result: dict[str, set[str]] = {}
    for row in rows:
        if not isinstance(row, dict) or not row.get("id"):
            continue
        values = row.get("values")
        if isinstance(values, list):
            result[str(row["id"])] = {str(value) for value in values}
    return result


def _task_ids(path: Path) -> list[str]:
    payload = _load_json(path)
    if not isinstance(payload, list) or not payload:
        raise ExperimentDefinitionError(f"Task file must contain a non-empty list: {path}")
    ids: list[str] = []
    for index, task in enumerate(payload, start=1):
        task_id = task.get("task_id") if isinstance(task, dict) else None
        if not isinstance(task_id, str) or not re.fullmatch(r"[0-9a-f]{40}", task_id):
            raise ExperimentDefinitionError(f"Task #{index} has an invalid task_id")
        ids.append(task_id)
    if len(ids) != len(set(ids)):
        raise ExperimentDefinitionError("Task IDs are not unique")
    return ids


def _nonempty_strings(value: Any, *, field: str) -> list[str]:
    if not isinstance(value, list) or not value:
        raise ExperimentDefinitionError(f"{field} must be a non-empty list")
    if any(not isinstance(item, str) or not item.strip() for item in value):
        raise ExperimentDefinitionError(f"{field} entries must be non-empty strings")
    return [item.strip() for item in value]


def validate_protocol(
    protocol: Any, *, catalog: dict[str, set[str]], task_ids: list[str]
) -> dict[str, Any]:
    if not isinstance(protocol, dict):
        raise ExperimentDefinitionError("Protocol must contain an object")
    if protocol.get("schema_version") != "personacuabench.matched-pair.v1":
        raise ExperimentDefinitionError("Unsupported protocol schema_version")
    experiment_id = protocol.get("experiment_id")
    if not isinstance(experiment_id, str) or not experiment_id.strip():
        raise ExperimentDefinitionError("experiment_id must be non-empty")

    baseline = protocol.get("baseline_dimensions")
    if not isinstance(baseline, dict) or not baseline:
        raise ExperimentDefinitionError("baseline_dimensions must be a non-empty object")
    for dimension, value in baseline.items():
        if dimension not in catalog:
            raise ExperimentDefinitionError(f"Unknown baseline dimension: {dimension}")
        if value not in catalog[dimension]:
            raise ExperimentDefinitionError(
                f"Invalid baseline {dimension}={value!r}"
            )

    scoring = protocol.get("scoring")
    if not isinstance(scoring, dict):
        raise ExperimentDefinitionError("scoring must be an object")
    score_scale = scoring.get("per_arm_scale")
    if not isinstance(score_scale, dict) or set(score_scale) != {"0", "1", "2"}:
        raise ExperimentDefinitionError("per_arm_scale must define 0, 1, and 2")

    axes = protocol.get("axes")
    if not isinstance(axes, list) or not 4 <= len(axes) <= 6:
        raise ExperimentDefinitionError("axes must contain between four and six entries")
    declared_count = (protocol.get("design") or {}).get("selected_axis_count")
    if declared_count != len(axes):
        raise ExperimentDefinitionError("selected_axis_count differs from axes length")

    seen_axis_ids: set[str] = set()
    seen_dimensions: set[str] = set()
    task_axis_counts: Counter[str] = Counter()
    for index, axis in enumerate(axes, start=1):
        if not isinstance(axis, dict):
            raise ExperimentDefinitionError(f"Axis #{index} must be an object")
        axis_id = axis.get("axis_id")
        if not isinstance(axis_id, str) or not re.fullmatch(r"[a-z][a-z0-9_]*", axis_id):
            raise ExperimentDefinitionError(f"Axis #{index} has invalid axis_id")
        if axis_id in seen_axis_ids:
            raise ExperimentDefinitionError(f"Duplicate axis_id: {axis_id}")
        seen_axis_ids.add(axis_id)
        dimension = axis.get("dimension")
        if dimension not in baseline:
            raise ExperimentDefinitionError(
                f"{axis_id}: target dimension must be present in baseline_dimensions"
            )
        if dimension in seen_dimensions:
            raise ExperimentDefinitionError(f"Duplicate target dimension: {dimension}")
        seen_dimensions.add(str(dimension))

        values: list[str] = []
        for arm_name in ("positive", "negative"):
            arm = axis.get(arm_name)
            if not isinstance(arm, dict):
                raise ExperimentDefinitionError(f"{axis_id}/{arm_name} must be an object")
            value = arm.get("value")
            if value not in catalog[str(dimension)]:
                raise ExperimentDefinitionError(
                    f"{axis_id}/{arm_name}: invalid {dimension}={value!r}"
                )
            values.append(str(value))
            if not str(arm.get("behavioral_definition", "")).strip():
                raise ExperimentDefinitionError(
                    f"{axis_id}/{arm_name} has no behavioral_definition"
                )
            _nonempty_strings(
                arm.get("generic_observables"),
                field=f"{axis_id}/{arm_name}/generic_observables",
            )
            _nonempty_strings(
                arm.get("contradictions"),
                field=f"{axis_id}/{arm_name}/contradictions",
            )
        if values[0] == values[1]:
            raise ExperimentDefinitionError(f"{axis_id}: arm values must differ")

        criteria = axis.get("tasks")
        if not isinstance(criteria, dict) or not criteria:
            raise ExperimentDefinitionError(f"{axis_id}: tasks must be non-empty")
        unknown = set(criteria) - set(task_ids)
        if unknown:
            raise ExperimentDefinitionError(
                f"{axis_id}: unknown task IDs: {sorted(unknown)}"
            )
        for task_id, criterion in criteria.items():
            if not isinstance(criterion, dict):
                raise ExperimentDefinitionError(
                    f"{axis_id}/{task_id}: criterion must be an object"
                )
            for field in (
                "inherited_task_signals",
                "positive_observables",
                "negative_observables",
            ):
                _nonempty_strings(
                    criterion.get(field), field=f"{axis_id}/{task_id}/{field}"
                )
            task_axis_counts[task_id] += 1

    uncovered = set(task_ids) - set(task_axis_counts)
    if uncovered:
        raise ExperimentDefinitionError(f"Tasks without persona axes: {sorted(uncovered)}")
    task_axis_total = sum(task_axis_counts.values())
    design = protocol.get("design") or {}
    if design.get("expected_task_axis_pairs_per_replicate") != task_axis_total:
        raise ExperimentDefinitionError(
            "expected_task_axis_pairs_per_replicate differs from the protocol matrix"
        )
    if design.get("expected_run_cells_per_replicate") != task_axis_total * 2:
        raise ExperimentDefinitionError(
            "expected_run_cells_per_replicate must be two times the task-axis count"
        )
    return protocol


def expected_profiles(protocol: dict[str, Any], *, protocol_sha256: str) -> dict[str, Any]:
    profiles: dict[str, Any] = {}
    baseline = protocol["baseline_dimensions"]
    for axis in protocol["axes"]:
        axis_id = axis["axis_id"]
        dimension = axis["dimension"]
        for arm_name in ("positive", "negative"):
            opposite = "negative" if arm_name == "positive" else "positive"
            arm = axis[arm_name]
            stem = f"mp_{axis_id}_{arm_name}"
            persona_id = stem.replace("_", "-")
            counterpart_id = f"mp-{axis_id.replace('_', '-')}-{opposite}"
            dimensions = dict(baseline)
            dimensions[dimension] = arm["value"]
            profiles[stem] = {
                "persona_id": persona_id,
                "version": "1.0",
                "source": "synthetic:controlled-matched-pair",
                "display_name": "Matched-pair shopper",
                "experimental_profile": True,
                "matched_pair": {
                    "schema_version": protocol["schema_version"],
                    "experiment_id": protocol["experiment_id"],
                    "protocol_path": "personacuabench/persona_experiment.json",
                    "protocol_sha256": protocol_sha256,
                    "pair_id": f"pair-{axis_id.replace('_', '-')}",
                    "axis_id": axis_id,
                    "axis_label": axis["label"],
                    "arm": arm_name,
                    "counterpart_persona_id": counterpart_id,
                    "changed_dimension": dimension,
                    "applicable_task_ids": list(axis["tasks"]),
                },
                "evaluation_dimensions": [dimension],
                "dimensions": dimensions,
            }
    return profiles


def _render(payload: dict[str, Any]) -> str:
    return HEADER + yaml.safe_dump(
        payload,
        sort_keys=False,
        allow_unicode=True,
        default_flow_style=False,
        width=100,
    )


def _atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary_name = tempfile.mkstemp(prefix=f".{path.name}.", dir=path.parent)
    temporary = Path(temporary_name)
    try:
        os.fchmod(fd, 0o644)
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temporary, path)
    finally:
        if temporary.exists():
            temporary.unlink()


def generate(
    profiles: dict[str, Any], *, output_dir: Path, check: bool
) -> list[Path]:
    paths: list[Path] = []
    mismatches: list[Path] = []
    expected_names = {f"{stem}.yaml" for stem in profiles}
    for stem, expected in profiles.items():
        path = output_dir / f"{stem}.yaml"
        paths.append(path)
        if check:
            try:
                actual = yaml.safe_load(path.read_text(encoding="utf-8"))
            except (FileNotFoundError, yaml.YAMLError):
                mismatches.append(path)
                continue
            if actual != expected:
                mismatches.append(path)
        else:
            _atomic_write(path, _render(expected))

    if output_dir.is_dir():
        extras = sorted(
            path for path in output_dir.glob("*.yaml") if path.name not in expected_names
        )
        mismatches.extend(extras)
    if mismatches:
        joined = "\n  ".join(str(path) for path in mismatches)
        raise ExperimentDefinitionError(
            "Generated matched-pair profiles are missing, stale, or unexpected:\n  "
            + joined
        )
    return paths


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--protocol", type=Path, default=DEFAULT_PROTOCOL_PATH)
    parser.add_argument("--tasks", type=Path, default=DEFAULT_TASKS_PATH)
    parser.add_argument("--schema", type=Path, default=DEFAULT_SCHEMA_PATH)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate the protocol and confirm checked-in YAML is current",
    )
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    protocol_path = args.protocol.expanduser().resolve()
    protocol = validate_protocol(
        _load_json(protocol_path),
        catalog=_catalog(args.schema.expanduser().resolve()),
        task_ids=_task_ids(args.tasks.expanduser().resolve()),
    )
    profiles = expected_profiles(
        protocol, protocol_sha256=_file_sha256(protocol_path)
    )
    paths = generate(
        profiles,
        output_dir=args.output_dir.expanduser().resolve(),
        check=args.check,
    )
    verb = "checked" if args.check else "wrote"
    print(
        f"{verb} {len(paths)} profiles across {len(protocol['axes'])} matched pairs"
    )
    for path in paths:
        print(f"{verb}: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
